// Generates src/demo/data.ts from the synthetic fixtures so that `db-preflight demo` runs
// with no files, no database and no network. A unit test fails if the output is stale.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");

function prismaSources(root) {
  const st = statSync(root);
  if (st.isFile()) return [{ path: root.split(/[\\/]/).pop(), text: read(root) }];
  const out = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (name.endsWith(".prisma")) out.push({ path: relative(root, p).split("\\").join("/"), text: read(p) });
    }
  };
  walk(root);
  return out;
}
function read(p) {
  return readFileSync(p, "utf8").replace(/\r\n/g, "\n");
}

export function renderDemoData() {
  const scenarios = {
    broken: "composite-one-to-one-mismatch",
    healthy: "healthy",
  };
  let body = "";
  for (const [name, dir] of Object.entries(scenarios)) {
    const manifest = JSON.parse(read(join(repo, "fixtures", dir, "fixture.json")));
    const sources = prismaSources(join(repo, "fixtures", dir, manifest.schema));
    const snapshot = JSON.parse(read(join(repo, "fixtures", dir, manifest.snapshot)));
    body += `  ${name}: {\n    fixture: ${JSON.stringify(dir)},\n    defaultSchema: ${JSON.stringify(manifest.defaultSchema)},\n    inputKind: ${JSON.stringify(statSync(join(repo, "fixtures", dir, manifest.schema)).isFile() ? "file" : "directory")},\n    sources: ${JSON.stringify(sources, null, 2).replace(/\n/g, "\n    ")},\n    snapshot: ${JSON.stringify(snapshot)} as unknown,\n  },\n`;
  }
  return `// GENERATED by scripts/gen-demo-data.mjs from fixtures/. Do not edit by hand.\n// All data is synthetic.\n\nexport interface DemoScenario {\n  fixture: string;\n  defaultSchema: string;\n  inputKind: "file" | "directory";\n  sources: { path: string; text: string }[];\n  snapshot: unknown;\n}\n\nexport const DEMO_SCENARIOS: Record<"broken" | "healthy", DemoScenario> = {\n${body}};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(repo, "src", "demo", "data.ts"), renderDemoData());
  console.log("wrote src/demo/data.ts");
}
