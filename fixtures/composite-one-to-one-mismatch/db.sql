CREATE TABLE public.organizations (
  id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL
);

CREATE TABLE public.monthly_snapshots (
  organization_id integer NOT NULL REFERENCES public.organizations (id),
  month           char(7) NOT NULL,
  snapshot_id     integer NOT NULL,
  created_at      timestamp(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT monthly_snapshots_pkey PRIMARY KEY (organization_id, month, snapshot_id)
);

CREATE TABLE public.snapshot_summaries (
  id              integer GENERATED BY DEFAULT AS IDENTITY,
  organization_id integer NOT NULL,
  month           char(7) NOT NULL,
  snapshot_id     integer NOT NULL,
  total_amount    numeric(12, 2) NOT NULL,
  note            text,
  CONSTRAINT snapshot_summaries_pkey PRIMARY KEY (id),
  CONSTRAINT snapshot_summaries_snapshot_fkey FOREIGN KEY (organization_id, month, snapshot_id)
    REFERENCES public.monthly_snapshots (organization_id, month, snapshot_id) ON DELETE CASCADE
);

-- Non-unique index only: the FK triple is NOT unique.
CREATE INDEX snapshot_summaries_organization_id_month_snapshot_id_idx
  ON public.snapshot_summaries (organization_id, month, snapshot_id);

